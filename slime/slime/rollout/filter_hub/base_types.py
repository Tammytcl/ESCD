from collections import Counter, defaultdict
from dataclasses import dataclass
import hashlib
import math


def _flatten_samples(samples):
    """Flatten one level of fan-out without retaining model payloads."""

    flattened = []
    for sample in samples:
        if isinstance(sample, (list, tuple)):
            flattened.extend(sample)
        else:
            flattened.append(sample)
    return flattened


def _status_value(sample):
    status = getattr(sample, "status", None)
    return getattr(status, "value", status)


def _tail_ngram_repeat_coverage(text: str, *, n: int = 8, tail_chars: int = 2000) -> float:
    """Fraction of tail n-grams that occur more than once.

    This deliberately complements the legacy zlib repetition flag.  Character
    n-grams catch symbolic/formula loops that may compress poorly and therefore
    evade a compression-ratio threshold.  It is a diagnostic, not a semantic
    repetition classifier.
    """

    tail = str(text or "")[-tail_chars:]
    if len(tail) < n:
        return 0.0
    grams = [tail[offset : offset + n] for offset in range(len(tail) - n + 1)]
    counts = Counter(grams)
    return sum(counts[gram] > 1 for gram in grams) / len(grams)


def _finite_scalar(value):
    """Return a JSON/W&B-safe scalar, or None for non-scalars/non-finite values."""

    if isinstance(value, bool):
        return bool(value)
    if isinstance(value, int):
        return int(value)
    if isinstance(value, float):
        return value if math.isfinite(value) else None
    # numpy scalar and tensor scalar values expose item().  Keep this optional
    # so the filter module does not require torch/numpy imports.
    item = getattr(value, "item", None)
    if callable(item):
        try:
            scalar = item()
        except Exception:
            return None
        if isinstance(scalar, (bool, int)):
            return scalar
        if isinstance(scalar, float):
            return scalar if math.isfinite(scalar) else None
    return None


def build_raw_sample_record(sample, *, retained: bool | None, filter_reason: str | None) -> dict:
    """Build a bounded, text-facing pre-filter diagnostic record.

    Hidden states, token ids and full reward payloads are intentionally not
    copied.  They remain in the existing debug .pt artifact; this sidecar is
    safe to stream for every raw candidate generated by a long rollout.
    """

    response = str(getattr(sample, "response", "") or "")
    prompt = getattr(sample, "raw_prompt", None)
    if prompt is None:
        prompt = getattr(sample, "prompt", "")
    prompt_text = str(prompt or "")
    reward = getattr(sample, "reward", None)
    scalar_reward = {}
    alignment = {}
    if isinstance(reward, dict):
        for key, value in reward.items():
            scalar = _finite_scalar(value)
            if scalar is not None and (
                key in {"reward", "task_reward"}
                or key.startswith("teacher_cross_")
                or "entropy" in key
                or "mass" in key
                or "coverage" in key
            ):
                scalar_reward[str(key)] = scalar
            if key == "teacher_cross_skipped_mask":
                try:
                    values = [bool(item) for item in value]
                except (TypeError, ValueError):
                    values = [bool(value)]
                alignment["skipped_tokens"] = int(sum(values))
                alignment["total_tokens"] = int(len(values))
            elif key.startswith("teacher_cross_") and hasattr(value, "__len__"):
                try:
                    alignment[f"{key}_length"] = int(len(value))
                except TypeError:
                    pass

    if retained is not None:
        # Legacy filters may return a zero-dimensional torch/numpy boolean.
        # Normalize it before json.dump so diagnostics never alter training.
        try:
            retained = bool(retained)
        except (TypeError, ValueError):
            retained = None

    record = {
        "sample_index": getattr(sample, "index", None),
        "group_index": getattr(sample, "group_index", None),
        "rollout_id": getattr(sample, "rollout_id", None),
        "status": _status_value(sample),
        "retained": retained,
        "filter_reason": filter_reason,
        "prompt_chars": len(prompt_text),
        "response_chars": len(response),
        "response_tokens": int(getattr(sample, "response_length", 0) or 0),
        "effective_response_tokens": int(getattr(sample, "effective_response_length", 0) or 0),
        "raw_text_sha256": hashlib.sha256(response.encode("utf-8")).hexdigest(),
        "tail_8gram_repeat_coverage": _tail_ngram_repeat_coverage(response),
        "response": response,
    }
    if scalar_reward:
        record["scalar_reward"] = scalar_reward
    metadata = getattr(sample, "metadata", None)
    horizon = metadata.get("rollout_horizon") if isinstance(metadata, dict) else None
    if horizon is not None:
        record["rollout_horizon"] = dict(horizon)
    if alignment:
        record["alignment"] = alignment
    return record


@dataclass
class DynamicFilterOutput:
    keep: bool
    reason: str | None = None


def call_dynamic_filter(fn, *args, **kwargs):
    if fn is None:
        return DynamicFilterOutput(keep=True)

    output = fn(*args, **kwargs)

    # compatibility for legacy version
    if not isinstance(output, DynamicFilterOutput):
        output = DynamicFilterOutput(keep=output)

    return output


class MetricGatherer:
    def __init__(self):
        self._dynamic_filter_drop_reason_count = defaultdict(lambda: 0)
        self._generated_sample_count = 0
        self._truncated_sample_count = 0
        self._retained_sample_count = 0
        self._raw_response_lengths = []
        self._raw_repeat_coverages = []

    def on_rollout_group(self, samples):
        """Record generation outcomes before dynamic filtering.

        The final training batch contains only accepted groups, which used to
        hide truncation once a filter rejected it.  Counting here preserves a
        denominator over every generated sample, including rejected groups.
        """

        flattened = _flatten_samples(samples)
        self._generated_sample_count += len(flattened)
        self._raw_response_lengths.extend(int(getattr(sample, "response_length", 0) or 0) for sample in flattened)
        self._raw_repeat_coverages.extend(
            _tail_ngram_repeat_coverage(getattr(sample, "response", "")) for sample in flattened
        )
        self._truncated_sample_count += sum(
            1
            for sample in flattened
            if _status_value(sample) == "truncated"
        )

    def on_dynamic_filter_result(self, samples, *, keep: bool, reason: str | None = None):
        """Record whether a pre-filter group entered the training batch."""

        try:
            keep = bool(keep)
        except (TypeError, ValueError):
            keep = False
        if keep:
            self._retained_sample_count += len(_flatten_samples(samples))
        else:
            self.on_dynamic_filter_drop(reason)

    def on_dynamic_filter_drop(self, reason: str | None):
        if not reason:
            return
        self._dynamic_filter_drop_reason_count[reason] += 1

    def collect(self):
        metrics = {
            f"rollout/dynamic_filter/drop_{reason}": count
            for reason, count in self._dynamic_filter_drop_reason_count.items()
        }
        if self._generated_sample_count:
            metrics["rollout/generated_samples"] = self._generated_sample_count
            metrics["rollout/truncated_samples"] = self._truncated_sample_count
            metrics["rollout/truncated_ratio_all_generated"] = (
                self._truncated_sample_count / self._generated_sample_count
            )
            metrics["rollout/raw/response_tokens_p50"] = _percentile(self._raw_response_lengths, 0.50)
            metrics["rollout/raw/response_tokens_p90"] = _percentile(self._raw_response_lengths, 0.90)
            metrics["rollout/raw/response_tokens_p99"] = _percentile(self._raw_response_lengths, 0.99)
            metrics["rollout/raw/tail_8gram_repeat_coverage_mean"] = sum(self._raw_repeat_coverages) / len(
                self._raw_repeat_coverages
            )
            metrics["rollout/raw/tail_8gram_repeat_coverage_max"] = max(self._raw_repeat_coverages, default=0.0)
            metrics["rollout/retained_samples"] = self._retained_sample_count
            metrics["rollout/filter/replenishment_ratio"] = (
                self._generated_sample_count / self._retained_sample_count
                if self._retained_sample_count
                else float("inf")
            )
        return metrics


def _percentile(values, quantile: float) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    index = min(len(ordered) - 1, max(0, math.ceil(quantile * len(ordered)) - 1))
    return float(ordered[index])
